namespace SIL.Motif.Generator.Emit;

/// <summary>
/// Emits one <c>Operations/Generated4/{DeclaringClass}{FieldName}.g.cs</c> file for a basic-Integer-enum
/// field: two kind constants, two closed payload parsers — the <c>set</c> one also range-checking the
/// value against the field's <see cref="IntegerEnumFieldSpec.EnumMembers"/> — two lowering methods, and
/// two <see cref="Runner.Operations.IOperationHandler"/> implementations. The direct analogue of
/// <see cref="BooleanFieldEmitter"/>, generalized to any target class/field of this shape.
/// </summary>
/// <remarks>
/// The range check is the point of this shape existing separately from <see cref="BooleanFieldEmitter"/>:
/// LibLCM's own <c>WfiWordform.ValidateSpellingStatus</c> exists but a caller must not depend on it to
/// silently fix an out-of-range value, so the generated payload parser throws on one before it ever
/// reaches a lowering call. <c>clear</c> writes the enum's zero member, which is guaranteed to be one
/// of the confirmed values — so the two verbs cannot disagree about what is legal.
/// </remarks>
