using System.Text;

namespace SIL.Motif.Generator.Emit;

/// <summary>
/// Emits <c>SIL.Motif.Model/Snapshot/SnapshotFields.Generated.g.cs</c>: one constant per field this
/// slice emits, <em>except</em> <c>LexSense.Gloss</c> — its constant, <c>LexSenseGloss</c>, is
/// hand-written and stays in the hand-written half of the <c>partial class</c>
/// (<c>SnapshotFields.cs</c>), unchanged, because nothing about regenerating it requires moving it.
/// </summary>
public static class SnapshotFieldsEmitter
{
    public static string Render(IReadOnlyList<BasicFieldSpec> fieldsExcludingGloss)
    {
        var body = new StringBuilder();
        foreach (var field in fieldsExcludingGloss.OrderBy(f => f.SnapshotFieldConstant, StringComparer.Ordinal))
        {
            body.AppendLine(
                $"    /// <summary>A <c>{field.DeclaringClass}</c>'s <c>{field.FieldName}</c> {field.Sig} field.</summary>");
            body.AppendLine(
                $"    public const string {field.SnapshotFieldConstant} = \"{field.Group}/{field.Construct}/{LowerFirst(field.FieldName)}\";");
            body.AppendLine();
        }

        return Template.Replace("__BODY__", body.ToString().TrimEnd('\r', '\n'));
    }

    private static string LowerFirst(string value) => char.ToLowerInvariant(value[0]) + value[1..];

    private const string Template = """
        // <auto-generated>
        //   Produced by SIL.Motif.Generator's `emit` command.
        //   Do NOT hand-edit. Rerun `dotnet run --project src/SIL.Motif.Generator -- emit` after a
        //   manifest or MasterLCModel.xml change, and check in the result.
        // </auto-generated>
        namespace SIL.Motif.Model.Snapshot;

        public static partial class SnapshotFields
        {
        __BODY__
        }

        """;
}
